// Download source cards once; publish full-resolution WebP assets. Requires cwebp.
import { readFile, writeFile, mkdir, access, stat } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { ROLE_CATALOG } from '../src/catalog/roles.ts';
const cards = JSON.parse(await readFile('cards.json', 'utf8'));
await mkdir('data/source-cards', { recursive: true });
await mkdir('public/offline-cards', { recursive: true });
const queue = [...ROLE_CATALOG];
const map = {};
let original = 0, compressed = 0;
async function worker() {
  while (queue.length) {
    const entry = queue.shift();
    const source = `data/source-cards/${entry.id}.png`;
    try { await access(source); } catch {
      try { await writeFile(source, await readFile(`public/offline-cards/${entry.id}.png`)); }
      catch {
        const url = cards[entry.source.group]['Deck of cards'][entry.source.name]['Image Url'];
        const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
        if (!response.ok) throw new Error(`${entry.id}: ${response.status}`);
        await writeFile(source, new Uint8Array(await response.arrayBuffer()));
      }
    }
    const output = `public/offline-cards/${entry.id}.webp`;
    execFileSync('cwebp', ['-quiet', '-q', '88', '-m', '6', source, '-o', output]);
    original += (await stat(source)).size; compressed += (await stat(output)).size;
    map[entry.id] = `/offline-cards/${entry.id}.webp`;
  }
}
await Promise.all(Array.from({ length: 4 }, worker));
const ordered = Object.fromEntries(ROLE_CATALOG.map(r => [r.id, map[r.id]]));
await writeFile('src/catalog/images.ts', '// Generated by scripts/generate-role-images.mjs. Full-resolution local WebP.\nexport const ROLE_IMAGES: Record<string, string> = ' + JSON.stringify(ordered, null, 2) + ';\n');
console.log(JSON.stringify({ cards: Object.keys(map).length, original, compressed }));
