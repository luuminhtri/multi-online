// Generates src/catalog/images.ts from cards.json via the catalog's 1-1 source map.
// Read-only against source data. Run: node scripts/generate-role-images.mjs
import { readFileSync } from 'node:fs';
import { open } from 'node:fs/promises';
import { ROLE_CATALOG } from '../src/catalog/roles.ts';

const root = new URL('../', import.meta.url);
const cards = JSON.parse(await readFileSync(new URL('cards.json', root), 'utf8'));

const lines = [];
const missing = [];
for (const entry of ROLE_CATALOG) {
  const deck = cards[entry.source.group]?.['Deck of cards'] ?? {};
  const card = deck[entry.source.name];
  const image = card && typeof card === 'object' ? card['Image Url'] : undefined;
  if (typeof image !== 'string' || !image.startsWith('https://')) { missing.push(`${entry.source.group}/${entry.source.name}`); continue; }
  lines.push(`  ${JSON.stringify(entry.id)}: ${JSON.stringify(image)},`);
}
if (missing.length) throw new Error(`Thiếu Image Url hợp lệ cho: ${missing.join(', ')}`);

const body = `// Generated by scripts/generate-role-images.mjs from cards.json. Do not edit by hand.
// Images stay on their source host; the UI falls back to initials when a URL fails to load.
export const ROLE_IMAGES: Record<string, string> = {
${lines.join('\n')}
};
`;
const target = new URL('src/catalog/images.ts', root);
const handle = await open(target, 'w');
try { await handle.writeFile(body); await handle.sync(); } finally { await handle.close(); }
console.log(`Đã ghi ${lines.length} ảnh vào src/catalog/images.ts`);
